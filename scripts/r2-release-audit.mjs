 const mobile=await browser.newContext({viewport:{width:844,height:390},deviceScaleFactor:2,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
 const mp=await mobile.newPage();mp.on('pageerror',e=>report.errors.push(String(e)));
 await mp.goto(process.argv[2]||'http://localhost:4173/');
